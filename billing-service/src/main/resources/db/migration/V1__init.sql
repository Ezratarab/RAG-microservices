-- billing-service schema. Money is NUMBER(12,2); customers are Keycloak user ids.
CREATE SEQUENCE PAYMENT_SEQ START WITH 1 INCREMENT BY 1;

CREATE TABLE BILLING_PAYMENT (
    ID            NUMBER(19)    PRIMARY KEY,
    CUSTOMER_ID   VARCHAR2(36)  NOT NULL,
    BILL_PRICE    NUMBER(12, 2) NOT NULL,
    PAYMENT_TOKEN VARCHAR2(255) NOT NULL
);
CREATE INDEX IX_BILLING_PAYMENT_CUSTOMER ON BILLING_PAYMENT (CUSTOMER_ID);

CREATE TABLE BILLING_USER_USAGE (
    ID          NUMBER(19) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    CUSTOMER_ID VARCHAR2(36)  NOT NULL,
    AMOUNT      NUMBER(12, 2) DEFAULT 0 NOT NULL,
    CONSTRAINT UK_BILLING_USAGE_CUSTOMER UNIQUE (CUSTOMER_ID)
);

-- Usage events already billed (makes the Kafka consumer idempotent)
CREATE TABLE PROCESSED_EVENT (
    EVENT_ID     VARCHAR2(36) PRIMARY KEY,
    PROCESSED_AT TIMESTAMP WITH TIME ZONE NOT NULL  -- Hibernate maps Instant to a UTC timestamp
);
